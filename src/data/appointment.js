// Hàm helper để lấy appointments theo ngày
export const getAppointmentsByDate = (date) => {
  return mockAppointments.filter(apt => apt.appointmentDate === date);
};

// Hàm helper để lấy số lượng appointments theo slot
export const getAppointmentCountBySlot = (date, time) => {
  return mockAppointments.filter(
    apt => apt.appointmentDate === date && 
           apt.appointmentTime === time &&
           apt.status !== 'cancelled'
  ).length;
};

// Hàm helper để lấy thông tin status
export const getStatusInfo = (statusValue) => {
  return appointmentStatuses.find(s => s.value === statusValue) || appointmentStatuses[0];
};
